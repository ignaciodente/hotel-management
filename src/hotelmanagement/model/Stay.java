package hotelmanagement.model;

import hotelmanagement.interfaces.Identifiable;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * Occupation of a room, from check-in to check-out.
 * It is created at check-in and closed at check-out.
 */
public class Stay implements Identifiable {

    private int stayId;
    private Reservation reservation;
    private List<Guest> occupants;
    private LocalDateTime checkInDate;
    private LocalDateTime checkOutDate;
    private Double totalAmount;

    /**
     * Creates a new active stay at check-in, not saved in the database yet (id 0).
     */
    public Stay(Reservation reservation, List<Guest> occupants, LocalDateTime checkInDate) {
        this.reservation = reservation;
        this.occupants = new ArrayList<>(occupants);
        this.checkInDate = checkInDate;
        this.checkOutDate = null;
        this.totalAmount = null;
    }

    /**
     * Creates a stay loaded from the database. checkOutDate and totalAmount
     * are null while the stay is active.
     */
    public Stay(int stayId, Reservation reservation, List<Guest> occupants, LocalDateTime checkInDate,
                LocalDateTime checkOutDate, Double totalAmount) {
        this(reservation, occupants, checkInDate);
        this.stayId = stayId;
        this.checkOutDate = checkOutDate;
        this.totalAmount = totalAmount;
    }

    @Override
    public int getId() {
        return stayId;
    }

    /**
     * Sets the id generated by the database after inserting the stay.
     *
     * @param stayId the generated id
     */
    public void setId(int stayId) {
        this.stayId = stayId;
    }

    public Reservation getReservation() {
        return reservation;
    }

    /**
     * Returns the room of the stay, taken from its reservation.
     *
     * @return the occupied room
     */
    public Room getRoom() {
        return reservation.getRoom();
    }

    /**
     * Returns a copy of the occupants, so the list can only be changed through this class.
     *
     * @return the guests of the stay
     */
    public List<Guest> getOccupants() {
        return new ArrayList<>(occupants);
    }

    public LocalDateTime getCheckInDate() {
        return checkInDate;
    }

    public LocalDateTime getCheckOutDate() {
        return checkOutDate;
    }

    public Double getTotalAmount() {
        return totalAmount;
    }
}